"""Generate the canonical field descriptors and reference table."""

import argparse
import json
from pathlib import Path
import subprocess


def outputs(root):
    catalog = json.loads((root / "catalog/fields.json").read_text())
    code = ["(* Generated by tools/generate_fields.py from catalog/fields.json. *)"]
    docs = ["# Captured fields", "", "All fields below are acquired by the core snapshot schema on tmux 3.3+.",
            "Text operations compare bytes without normalization or case folding.", "",
            "| OCaml field | Value | tmux format |", "| --- | --- | --- |"]
    types = {"Bool": "bool", "Int": "int", "Text": "string"}
    for module, fields in catalog.items():
        code.append(f"module {module} = struct")
        for field, (kind, name, *accessor) in fields.items():
            get = accessor[0] if accessor else f"Graph.{module}.{field}"
            code.append(f'let {field} = Filter.Field.{{name = "{name}"; kind = {kind}; get = {get}}}')
            docs.append(f"| `{module}.Fields.{field}` | `{types[kind]}` | `{name}` |")
        code.append("let fields = [" + "; ".join(f"Filter.Field.Pack {name}" for name in fields) + "]")
        code.append("end")
    formatted = subprocess.run(
        ["ocamlformat", "--name", "lib/generated_fields.ml", "--impl", "-"],
        input="\n".join(code) + "\n", text=True, capture_output=True, check=True, cwd=root,
    ).stdout
    return {"lib/generated_fields.ml": formatted, "docs/fields.md": "\n".join(docs) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    for name, content in outputs(root).items():
        path = root / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"generated file differs: {name}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == "__main__":
    main()
