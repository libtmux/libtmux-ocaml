"""Capture upstream format catalogs and generate native availability metadata."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

VERSIONS = ["3.3", "3.3a", "3.4", "3.8"]
CONTEXTS = {"c": "Client", "client": "Connection", "s": "Session", "w": "Window",
            "wl": "Window_link", "wp": "Pane", "pb": "Buffer", "m": "Mouse", "item": "Command"}


def import_sources(directory):
    entries, sources = {}, {}
    for version in VERSIONS:
        raw = (directory / f"tmux-{version}/format.c").read_bytes()
        text = raw.decode()
        sources[version] = dict(url=f"https://github.com/tmux/tmux/blob/{version}/format.c",
                                sha256=hashlib.sha256(raw).hexdigest())
        table = text.split("static const struct format_table_entry format_table[] = {", 1)[1].split("\n};", 1)[0]
        matches = list(re.finditer(r'\{ "([a-z0-9_]+)", FORMAT_TABLE_(STRING|TIME),\s+(format_cb_\w+),?\s*\}', table))
        assert len(matches) == table.count('{ "')
        for match in matches:
            name, kind, callback = match.groups()
            function = re.search(r'\n' + callback + r'\([^\n]*\)\n\{(.*?)\n\}', text, re.S)
            assert function, callback
            contexts = sorted({CONTEXTS[member] for member in re.findall(r'ft->(\w+)', function.group(1)) if member in CONTEXTS})
            if not contexts:
                contexts = ["Server"]
            key = (name, kind, tuple(contexts))
            if key not in entries:
                entries[key] = dict(name=name, kind="Timestamp" if kind == "TIME" else "Text",
                                    contexts=contexts, versions=[])
            entries[key]["versions"].append(version)
    return dict(sources=sources, entries=sorted(entries.values(), key=lambda row: (row["name"], row["versions"])))


def outputs(root):
    catalog = json.loads((root / "catalog/formats.json").read_text())
    code = ["(* Generated by tools/generate_formats.py from catalog/formats.json. *)",
            "type kind = Text | Timestamp",
            "type context = Server | Connection | Session | Window | Window_link | Pane | Client | Buffer | Mouse | Command",
            "type descriptor = { name : string; kind : kind; contexts : context list; versions : string list }",
            "let versions = [" + "; ".join(json.dumps(version) for version in catalog["sources"]) + "]",
            "let entries = Iarray.of_list ["]
    docs = ["# Format availability", "", "Typed common fields are captured with the snapshot. `Formats.lookup` reads",
            "those captured values without I/O. It distinguishes `Value`, `Missing`,",
            "`Unacquired` and `Unsupported`; an empty captured string remains a value.", "",
            "The catalog below records upstream callbacks on each qualified release.",
            "Contexts are the callback's direct context dependencies, not a guarantee",
            "that a value exists. Callers such as hooks and menus add other variables",
            "outside this built-in catalog. The library does not silently acquire",
            "uncaptured fields or infer absence from an empty format expansion.", "",
            "| Format | Upstream kind | Contexts | Releases |", "| --- | --- | --- | --- |"]
    for row in catalog["entries"]:
        code.append('{ name = %s; kind = %s; contexts = [%s]; versions = [%s] };' %
                    (json.dumps(row["name"]), row["kind"], "; ".join(row["contexts"]),
                     "; ".join(json.dumps(version) for version in row["versions"])))
        docs.append(f'| `{row["name"]}` | {row["kind"]} | {", ".join(row["contexts"])} | {", ".join(row["versions"])} |')
    code.append("]")
    docs.extend(["", "## Sources", ""])
    for version, source in catalog["sources"].items():
        docs.append(f'- [tmux {version} format.c]({source["url"]}), SHA-256 `{source["sha256"]}`.')
    formatted = subprocess.run(["ocamlformat", "--name", "lib/format_catalog.ml", "--impl", "-"],
                               input="\n".join(code) + "\n", text=True, capture_output=True, check=True, cwd=root).stdout
    return {"lib/format_catalog.ml": formatted, "docs/formats.md": "\n".join(docs) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--source-dir", type=Path, help="Recapture exact release sources outside check loops")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    if args.source_dir:
        assert not args.check
        (root / "catalog/formats.json").write_text(json.dumps(import_sources(args.source_dir), indent=2) + "\n")
    for name, content in outputs(root).items():
        path = root / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"generated file differs: {name}")
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
