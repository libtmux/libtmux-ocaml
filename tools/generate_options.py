"""Generate option descriptors from a captured, versioned upstream catalog."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

VERSIONS = ["3.3", "3.3a", "3.4", "3.8"]
KINDS = dict(STRING="Text", NUMBER="Number", FLAG="Flag", CHOICE="Choice",
             KEY="Key", COLOUR="Colour", COMMAND="Commands")


def import_sources(directory):
    rows, sources = {}, {}
    for version in VERSIONS:
        path = directory / f"tmux-{version}/options-table.c"
        raw = path.read_bytes()
        text = raw.decode().split("const struct options_table_entry options_table[] = {", 1)[1]
        sources[version] = dict(url=f"https://github.com/tmux/tmux/blob/{version}/options-table.c",
                                sha256=hashlib.sha256(raw).hexdigest())
        entries = []
        for match in re.finditer(r'\{ \.name = "([a-z0-9-]+)",(.*?)\n\s*\},', text, re.S):
            name, body = match.groups()
            kind = re.search(r'\.type = OPTIONS_TABLE_(\w+)', body).group(1)
            scope = re.search(r'\.scope = ([^,]+)', body).group(1)
            scopes = re.findall(r'OPTIONS_TABLE_(SERVER|SESSION|WINDOW|PANE)', scope)
            assert scopes, name
            entries.append(dict(name=name, kind=KINDS[kind], scopes=scopes,
                                array="OPTIONS_TABLE_IS_ARRAY" in body,
                                hook="OPTIONS_TABLE_IS_HOOK" in body))
        for match in re.finditer(r'OPTIONS_TABLE_(AFTER_HOOK|PANE_HOOK|WINDOW_HOOK|HOOK)\("([a-z0-9-]+)"', text):
            kind, name = match.groups()
            if kind == "AFTER_HOOK":
                name = "after-" + name
            scopes = {"PANE_HOOK": ["WINDOW", "PANE"], "WINDOW_HOOK": ["WINDOW"]}.get(kind, ["SESSION"])
            entries.append(dict(name=name, kind="Commands", scopes=scopes, array=True, hook=True))
        names = [entry["name"] for entry in entries]
        expected = text.count('.name = "') + len(re.findall(r'^\s*OPTIONS_TABLE_\w+\(', text, re.M))
        assert len(names) == expected and len(set(names)) == len(names), (version, len(names), expected)
        for entry in entries:
            key = json.dumps(entry, sort_keys=True)
            if key not in rows:
                rows[key] = dict(entry, versions=[])
            rows[key]["versions"].append(version)
    return dict(sources=sources, entries=sorted(rows.values(), key=lambda row: (row["name"], row["versions"])))


def outputs(root):
    catalog = json.loads((root / "catalog/options.json").read_text())
    code = ["(* Generated by tools/generate_options.py from catalog/options.json. *)",
            "module Kind = struct type t = Text | Number | Flag | Choice | Key | Colour | Commands end",
            "type descriptor = { name : string; kind : Kind.t; array : bool; hook : bool;",
            "scopes : [ `Server | `Session | `Window | `Pane ] list; versions : string list }",
            "let entries = Iarray.of_list ["]
    docs = ["# Option and hook catalog", "", "Generated from pinned upstream option tables. Descriptors list exact",
            "captured releases; other releases need catalog qualification.", "",
            "Values retain tmux's scalar type and array indexes. User options have",
            "explicit `@` names and text values.", "", "| Name | Kind | Scopes | Releases |", "| --- | --- | --- | --- |"]
    for row in catalog["entries"]:
        scopes = "; ".join("`" + scope.capitalize() for scope in row["scopes"])
        versions = "; ".join(json.dumps(version) for version in row["versions"])
        code.append('{ name = %s; kind = Kind.%s; array = %s; hook = %s; scopes = [%s]; versions = [%s] };' %
                    (json.dumps(row["name"]), row["kind"], str(row["array"]).lower(), str(row["hook"]).lower(), scopes, versions))
        kind = row["kind"] + (" array" if row["array"] else "")
        docs.append(f'| `{row["name"]}` | {kind} | {", ".join(row["scopes"])} | {", ".join(row["versions"])} |')
    code.append("]")
    docs.extend(["", "## Sources", ""])
    for version, source in catalog["sources"].items():
        docs.append(f'- [tmux {version} options-table.c]({source["url"]}), SHA-256 `{source["sha256"]}`.')
    formatted = subprocess.run(["ocamlformat", "--name", "lib/option_catalog.ml", "--impl", "-"],
                               input="\n".join(code) + "\n", text=True, capture_output=True, check=True, cwd=root).stdout
    return {"lib/option_catalog.ml": formatted, "docs/options.md": "\n".join(docs) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--source-dir", type=Path, help="Recapture exact release sources outside check loops")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    if args.source_dir:
        assert not args.check
        (root / "catalog/options.json").write_text(json.dumps(import_sources(args.source_dir), indent=2) + "\n")
    for name, content in outputs(root).items():
        path = root / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"generated file differs: {name}")
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
