#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = []
# ///
"""Capture upstream format catalogs and generate native availability metadata."""

import hashlib
import json
import re
from collections.abc import Sequence
from pathlib import Path

import emit

CONTEXTS = {
    "c": "Client",
    "client": "Connection",
    "s": "Session",
    "w": "Window",
    "wl": "Window_link",
    "wp": "Pane",
    "pb": "Buffer",
    "m": "Mouse",
    "item": "Command",
}


def import_sources(directory: Path, root: Path = emit.ROOT) -> dict[str, object]:
    entries, sources = {}, {}
    for version in emit.releases(root):
        raw = (directory / f"tmux-{version}/format.c").read_bytes()
        text = raw.decode()
        sources[version] = {
            "url": f"https://github.com/tmux/tmux/blob/{version}/format.c",
            "sha256": hashlib.sha256(raw).hexdigest(),
        }
        table = text.split(
            "static const struct format_table_entry format_table[] = {", 1
        )[1].split("\n};", 1)[0]
        matches = list(
            re.finditer(
                r'\{ "([a-z0-9_]+)", FORMAT_TABLE_(STRING|TIME),\s+(format_cb_\w+),?\s*\}',
                table,
            )
        )
        assert len(matches) == table.count('{ "')
        for match in matches:
            name, kind, callback = match.groups()
            function = re.search(
                r"\n" + callback + r"\([^\n]*\)\n\{(.*?)\n\}", text, re.DOTALL
            )
            assert function, callback
            contexts = sorted(
                {
                    CONTEXTS[member]
                    for member in re.findall(r"ft->(\w+)", function.group(1))
                    if member in CONTEXTS
                }
            )
            if not contexts:
                contexts = ["Server"]
            key = (name, kind, tuple(contexts))
            if key not in entries:
                entries[key] = {
                    "name": name,
                    "kind": "Timestamp" if kind == "TIME" else "Text",
                    "contexts": contexts,
                    "versions": [],
                }
            entries[key]["versions"].append(version)
    return {
        "sources": sources,
        "entries": sorted(
            entries.values(), key=lambda row: (row["name"], row["versions"])
        ),
    }


def outputs(root: Path) -> dict[str, str]:
    catalog = json.loads((root / "catalog/formats.json").read_text())
    assert list(catalog["sources"]) == emit.releases(root), (
        "format catalog differs from supported releases"
    )
    code = [
        "(* Generated by scripts/generate/generate_formats.py from catalog/formats.json. *)",
        "type kind = Text | Timestamp",
        "type context = Server | Connection | Session | Window | Window_link | Pane | Client | Buffer | Mouse | Command",
        "type descriptor = { name : string; kind : kind; contexts : context list; versions : string list }",
        "let versions = ["
        + "; ".join(json.dumps(version) for version in catalog["sources"])
        + "]",
        "let entries = Iarray.of_list [",
    ]
    docs = [
        "# Format availability",
        "",
        "Typed common fields are captured with the snapshot. `Formats.lookup` reads",
        "those captured values without I/O. It distinguishes `Value`, `Missing`,",
        "`Unacquired` and `Unsupported`; an empty captured string remains a value.",
        "",
        "The catalog records upstream callbacks throughout tmux 3.3a–3.8.",  # noqa: RUF001  # emitted verbatim into the generated documentation
        "Contexts are the callback's direct context dependencies, not a guarantee",
        "that a value exists. Callers such as hooks and menus add other variables",
        "outside this built-in catalog. The library does not silently acquire",
        "uncaptured fields or infer absence from an empty format expansion.",
        "",
        "| Format | Upstream kind | Contexts | Releases |",
        "| --- | --- | --- | --- |",
    ]
    for row in catalog["entries"]:
        code.append(
            "{{ name = {}; kind = {}; contexts = [{}]; versions = [{}] }};".format(
                json.dumps(row["name"]),
                row["kind"],
                "; ".join(row["contexts"]),
                "; ".join(json.dumps(version) for version in row["versions"]),
            )
        )
        docs.append(
            f"| `{row['name']}` | {row['kind']} | {', '.join(row['contexts'])} | {', '.join(row['versions'])} |"
        )
    code.append("]")
    docs.extend(["", "## Sources", ""])
    for version, source in catalog["sources"].items():
        docs.append(
            f"- [tmux {version} format.c]({source['url']}), SHA-256 `{source['sha256']}`."
        )
    formatted = emit.ocamlformat(root, "lib/format_catalog.ml", "\n".join(code) + "\n")
    return {
        "lib/format_catalog.ml": formatted,
        "docs/formats.md": "\n".join(docs) + "\n",
    }


def main(argv: Sequence[str] | None = None, root: Path = emit.ROOT) -> None:
    emit.main(
        __doc__ or "",
        outputs,
        recapture=("catalog/formats.json", import_sources),
        argv=argv,
        root=root,
    )


if __name__ == "__main__":
    main()
