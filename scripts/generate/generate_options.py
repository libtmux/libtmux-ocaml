#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = []
# ///
"""Generate option descriptors from a captured, versioned upstream catalog."""

import hashlib
import json
import re
from collections.abc import Sequence
from pathlib import Path

import emit

KINDS = {
    "STRING": "Text",
    "NUMBER": "Number",
    "FLAG": "Flag",
    "CHOICE": "Choice",
    "KEY": "Key",
    "COLOUR": "Colour",
    "COMMAND": "Commands",
}


def import_sources(directory: Path, root: Path = emit.ROOT) -> dict[str, object]:
    rows, sources = {}, {}
    for version in emit.releases(root):
        path = directory / f"tmux-{version}/options-table.c"
        raw = path.read_bytes()
        text = raw.decode().split(
            "const struct options_table_entry options_table[] = {", 1
        )[1]
        sources[version] = {
            "url": f"https://github.com/tmux/tmux/blob/{version}/options-table.c",
            "sha256": hashlib.sha256(raw).hexdigest(),
        }
        entries = []
        for match in re.finditer(
            r'\{ \.name = "([a-z0-9-]+)",(.*?)\n\s*\},', text, re.DOTALL
        ):
            name, body = match.groups()
            kind_match = re.search(r"\.type = OPTIONS_TABLE_(\w+)", body)
            scope_match = re.search(r"\.scope = ([^,]+)", body)
            assert kind_match and scope_match, name
            kind = kind_match.group(1)
            scope = scope_match.group(1)
            scopes = re.findall(r"OPTIONS_TABLE_(SERVER|SESSION|WINDOW|PANE)", scope)
            assert scopes, name
            entries.append(
                {
                    "name": name,
                    "kind": KINDS[kind],
                    "scopes": scopes,
                    "array": "OPTIONS_TABLE_IS_ARRAY" in body,
                    "hook": "OPTIONS_TABLE_IS_HOOK" in body,
                }
            )
        for match in re.finditer(
            r'OPTIONS_TABLE_(AFTER_HOOK|PANE_HOOK|WINDOW_HOOK|HOOK)\("([a-z0-9-]+)"',
            text,
        ):
            kind, name = match.groups()
            if kind == "AFTER_HOOK":
                name = "after-" + name
            scopes = {"PANE_HOOK": ["WINDOW", "PANE"], "WINDOW_HOOK": ["WINDOW"]}.get(
                kind, ["SESSION"]
            )
            entries.append(
                {
                    "name": name,
                    "kind": "Commands",
                    "scopes": scopes,
                    "array": True,
                    "hook": True,
                }
            )
        names = [entry["name"] for entry in entries]
        expected = text.count('.name = "') + len(
            re.findall(r"^\s*OPTIONS_TABLE_\w+\(", text, re.MULTILINE)
        )
        assert len(names) == expected and len(set(names)) == len(names), (
            version,
            len(names),
            expected,
        )
        for entry in entries:
            key = json.dumps(entry, sort_keys=True)
            if key not in rows:
                rows[key] = dict(entry, versions=[])
            rows[key]["versions"].append(version)
    return {
        "sources": sources,
        "entries": sorted(
            rows.values(), key=lambda row: (row["name"], row["versions"])
        ),
    }


def outputs(root: Path) -> dict[str, str]:
    catalog = json.loads((root / "catalog/options.json").read_text())
    assert list(catalog["sources"]) == emit.releases(root), (
        "option catalog differs from supported releases"
    )
    code = [
        "(* Generated by scripts/generate/generate_options.py from catalog/options.json. *)",
        "module Kind = struct type t = Text | Number | Flag | Choice | Key | Colour | Commands end",
        "type descriptor = { name : string; kind : Kind.t; array : bool; hook : bool;",
        "scopes : [ `Server | `Session | `Window | `Pane ] list; versions : string list }",
        "let versions = ["
        + "; ".join(json.dumps(version) for version in catalog["sources"])
        + "]",
        "let entries = Iarray.of_list [",
    ]
    docs = [
        "# Option and hook catalog",
        "",
        "Generated from pinned upstream option tables. Descriptors list exact",
        "availability for every supported release from tmux 3.3a through 3.8.",
        "",
        "Values retain tmux's scalar type and array indexes. User options have",
        "explicit `@` names and text values.",
        "",
        "| Name | Kind | Scopes | Releases |",
        "| --- | --- | --- | --- |",
    ]
    for row in catalog["entries"]:
        scopes = "; ".join("`" + scope.capitalize() for scope in row["scopes"])
        versions = "; ".join(json.dumps(version) for version in row["versions"])
        code.append(
            "{{ name = {}; kind = Kind.{}; array = {}; hook = {}; scopes = [{}]; versions = [{}] }};".format(
                json.dumps(row["name"]),
                row["kind"],
                str(row["array"]).lower(),
                str(row["hook"]).lower(),
                scopes,
                versions,
            )
        )
        kind = row["kind"] + (" array" if row["array"] else "")
        docs.append(
            f"| `{row['name']}` | {kind} | {', '.join(row['scopes'])} | {', '.join(row['versions'])} |"
        )
    code.append("]")
    docs.extend(["", "## Sources", ""])
    for version, source in catalog["sources"].items():
        docs.append(
            f"- [tmux {version} options-table.c]({source['url']}), SHA-256 `{source['sha256']}`."
        )
    formatted = emit.ocamlformat(root, "lib/option_catalog.ml", "\n".join(code) + "\n")
    return {
        "lib/option_catalog.ml": formatted,
        "docs/options.md": "\n".join(docs) + "\n",
    }


def main(argv: Sequence[str] | None = None, root: Path = emit.ROOT) -> None:
    emit.main(
        __doc__ or "",
        outputs,
        recapture=("catalog/options.json", import_sources),
        argv=argv,
        root=root,
    )


if __name__ == "__main__":
    main()
